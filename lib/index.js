/**
 * Dispatch one fenced request onto the plugin's small JSON API.
 *
 * `GET  /list`                  → `{ files, active, disabled, dir }`
 * `GET  /read?name=<name>`      → `{ name, css }`
 * `GET  /history?name=<name>`   → `{ name, entries }`
 * `GET  /gallery`               → `{ dir, wallpapers }` (stored wallpaper images)
 * `GET  /wallpaper?name=<name>` → the image bytes, immutable-cached
 * `POST /write  {name, css}`    → write a sheet
 * `POST /create {name}`         → create an empty sheet (409 when it exists)
 * `POST /import {name, css}`    → store an imported sheet (overwrites)
 * `POST /active {name}`         → record the active sheet
 * `POST /toggle {name, enabled}` → switch one sheet on or off (its file stays)
 * `POST /open   {name}`         → hand the sheet to the OS default application
 * `POST /wallpaper-image {dataUrl}` → store an uploaded wallpaper, answering with its URL
 *
 * @param req - fenced request.
 * @param res - response to write.
 */
/**
 * The running DSH release (`{ version, commit }`), read lazily through this lookup, or null in a
 * composition that does not expose `clientModules`. Set once by {@link apply}; read by `/about` so a
 * bug report can name the DSH that broke something.
 *
 * Lazy on purpose: services activate around this plugin, and `clientModules` is not necessarily up
 * yet when `apply` runs — asked once at mount, the answer was `undefined` on a real instance (the
 * first version of this feature reported null on every request, which is how that was found).
 * Asking per request costs a property read and cannot be too early.
 * @type {(() => { version?: string, commit?: string } | null) | null}
 */
let readDshRelease = null;

async function handle(req, res) {
  const url = new URL(req.url ?? '/', 'http://dsh.internal');
  const route = url.pathname.slice(ROUTE.length) || '/';
  const method = req.method ?? 'GET';

  if (method === 'GET' && route === '/list') {
    const [files, book] = await Promise.all([listFiles(), readBookkeeping()]);
    // The active sheet is listed even past MAX_FILES. Without it the row cannot
    // find the sheet it should show and silently falls back to the first one.
    if (book.active !== undefined && !files.some(file => file.name === book.active)) {
      const stat = await fs.stat(path.join(stylesDir(), book.active)).catch(() => undefined);
      if (stat !== undefined && stat.isFile()) {
        files.push({ name: book.active, bytes: stat.size, mtime: Math.round(stat.mtimeMs) });
        files.sort((left, right) => left.name.localeCompare(right.name));
      }
    }
    // A switch whose sheet is gone is dropped, so the file never keeps ghosts.
    const listed = new Set(files.map(file => file.name));
    const disabled = book.disabled.filter(name => listed.has(name));
    json(res, 200, { ok: true, dir: stylesDir(), files, active: book.active ?? null, disabled });
    return;
  }

  if (method === 'GET' && route === '/read') {
    const name = url.searchParams.get('name');
    // A record is readable through this route — the wallpaper panel fetches its own record back —
    // but it is not a sheet, which is why the two resolvers exist side by side.
    const full = safePath(name) ?? safeRecordPath(name);
    if (full === undefined || await isSymlink(full)) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    const sheet = await readSheetWithRev(name);
    if (sheet === undefined) {
      // `optional=1` turns "there is no such file" into an ANSWER instead of a failure. The two
      // records (`wallpaper.json.css` / `settings.json.css`) are simply absent on a fresh install,
      // and a 404 for a file that is *supposed* to be optional is logged by the browser as an
      // error on every page load — noise that teaches people to ignore the console. The editor
      // never sends this flag, so a missing sheet is still a hard 404 there.
      if (url.searchParams.get('optional') === '1') {
        json(res, 200, { ok: true, name, css: '', rev: null, absent: true });
        return;
      }
      json(res, 404, { ok: false, error: 'not-found' });
      return;
    }
    json(res, 200, { ok: true, name, css: sheet.css, rev: sheet.rev });
    return;
  }

  if (method === 'GET' && route === '/history') {
    const name = url.searchParams.get('name');
    if (safePath(name) === undefined) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    json(res, 200, { ok: true, name, entries: await listSnapshots(name) });
    return;
  }

  if (method === 'GET' && route === '/gallery') {
    const wallpapers = await listWallpapers();
    json(res, 200, { ok: true, dir: wallpapersDir(), wallpapers });
    return;
  }

  if (method === 'GET' && route === '/about') {
    // What the HOST half is, read from the package that is actually installed rather than from a
    // constant in the source: a version string typed into a file is a version string that goes stale
    // the first time somebody edits package.json without editing the string. The About section shows
    // this next to the browser half's own version, so a half-updated install is visible instead of
    // mysterious.
    const manifest = await fs.readFile(new URL('../package.json', import.meta.url), 'utf8')
      .then(text => JSON.parse(text))
      .catch(() => undefined);
    // Asked per request, not once at mount: see `readDshRelease`.
    const release = readDshRelease?.() ?? null;
    json(res, 200, {
      ok: true,
      name: manifest?.name ?? 'dsh-custom-css',
      version: manifest?.version ?? null,
      description: manifest?.description ?? null,
      license: manifest?.license ?? null,
      repository: typeof manifest?.repository === 'string' ? manifest.repository : (manifest?.repository?.url ?? null),
      homepage: manifest?.homepage ?? null,
      dir: stylesDir(),
      // The two directories the records live in, so a user can be told where to look without the
      // browser half having to spell a path out.
      wallpapers: wallpapersDir(),
      node: process.version,
      platform: process.platform,
      // The running DSH release, when the host exposes it. It is the one number a bug report needs
      // and the browser half cannot learn on its own — `clientModules.release` is DSH's own record
      // of "which release am I", and a composition without that service simply reports null rather
      // than failing the whole route: the About section is informational either way.
      dsh: release?.version ?? null,
      dshCommit: release?.commit ?? null,    });
    return;
  }

  if (method === 'GET' && route === '/wallpaper') {
    const name = url.searchParams.get('name');
    const full = safeWallpaperPath(name);
    if (full === undefined) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    const bytes = await fs.readFile(full).catch(() => undefined);
    if (bytes === undefined) {
      json(res, 404, { ok: false, error: 'not-found' });
      return;
    }
    // The name is a content hash, so this answer can never go stale: `immutable` keeps the
    // wallpaper out of every later page load's request queue.
    res.writeHead(200, {
      'content-type': WALLPAPER_SERVED.get(path.extname(name)) ?? 'application/octet-stream',
      'content-length': bytes.length,
      'cache-control': 'private, max-age=31536000, immutable',
    });
    res.end(bytes);
    return;
  }

  if (method === 'GET' && route === '/export') {
    // Everything the plugin owns, as one JSON document: the sheets with their history, the two
    // records, and the pictures (base64, because that is what survives a clipboard and a file
    // alike). Listing is not enough — a backup that loses the history loses exactly the part a user
    // cannot retype.
    const dir = stylesDir();
    await fs.mkdir(dir, { recursive: true });
    const sheets = {};
    for (const file of await listFiles(Infinity)) {
      const css = await fs.readFile(path.join(dir, file.name), 'utf8').catch(() => undefined);
      if (css === undefined) continue;
      sheets[file.name] = { css, history: await listSnapshots(file.name) };
      for (const entry of sheets[file.name].history) {
        entry.css = await fs.readFile(path.join(snapshotDir(file.name), entry.stamp + '.css'), 'utf8').catch(() => undefined);
      }
    }
    const records = {};
    for (const name of [WALLPAPER_RECORD, SETTINGS_RECORD]) {
      const text = await fs.readFile(path.join(dir, name), 'utf8').catch(() => undefined);
      if (text !== undefined) records[name] = text;
    }
    const wallpapers = [];
    for (const entry of await listWallpapers()) {
      const bytes = await fs.readFile(path.join(wallpapersDir(), entry.name)).catch(() => undefined);
      if (bytes === undefined) continue;
      wallpapers.push({
        name: entry.name,
        bytes: entry.bytes,
        mtime: entry.mtime,
        dataUrl: 'data:' + (WALLPAPER_SERVED.get(path.extname(entry.name)) ?? 'application/octet-stream') + ';base64,' + bytes.toString('base64'),
      });
    }
    json(res, 200, {
      ok: true,
      kind: 'dsh-custom-css-backup',
      version: 1,
      exportedAt: new Date().toISOString(),
      dir,
      sheets,
      records,
      wallpapers,
    });
    return;
  }

  if (method !== 'POST') {
    json(res, 404, { ok: false, error: 'not-found' });
    return;
  }

  if (route === '/wallpaper-image') {
    // This one body is a whole picture, so it gets its own cap instead of the sheet cap. The
    // ceiling is set from the accepted size plus base64's 4/3 expansion, with room for the
    // data-url header — a body larger than that can only be a rejected upload anyway.
    const body = await readBody(req, Math.ceil(MAX_WALLPAPER_BYTES * 4 / 3) + 4096);
    if (body === undefined || typeof body !== 'object' || body === null) {
      json(res, 400, { ok: false, error: 'bad-body' });
      return;
    }
    const stored = await storeWallpaper(body.dataUrl);
    if (stored === undefined) {
      // One code for "not an image we take" and "too big", because the two are decided by the
      // same parse and the panel's copy for both is the same sentence.
      json(res, 400, { ok: false, error: 'bad-image' });
      return;
    }
    json(res, 200, {
      ok: true,
      name: stored.name,
      bytes: stored.bytes,
      reused: stored.reused,
      url: ROUTE + '/wallpaper?name=' + encodeURIComponent(stored.name),
    });
    return;
  }

  if (route === '/open-dir') {
    // No body: this route is a verb with a fixed object, so it is answered BEFORE the body is read.
    // (Reading first cost a 400 on an empty POST, which is the only shape this call has.)
    // The same launcher the row uses for one sheet, pointed at the directory: a folder is what the
    // file manager opens. Detached and unreferenced, so a refused launch never fails the route.
    await fs.mkdir(stylesDir(), { recursive: true });
    launchFile(stylesDir());
    json(res, 200, { ok: true, dir: stylesDir() });
    return;
  }

  const body = await readBody(req);
  if (body === undefined || typeof body !== 'object' || body === null) {
    json(res, 400, { ok: false, error: 'bad-body' });
    return;
  }

  if (route === '/write') {
    // A record (`*.json.css`) or a sheet, and the resolver decides which door applies. Asking
    // `safePath` alone would have refused the plugin's own `wallpaper.json.css` — the very call the
    // wallpaper panel makes on every change.
    const full = safePath(body.name) ?? safeRecordPath(body.name);
    if (full === undefined || await isSymlink(full)) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    if (typeof body.css !== 'string') {
      json(res, 400, { ok: false, error: 'bad-css' });
      return;
    }
    await fs.mkdir(stylesDir(), { recursive: true });
    // Whatever is being replaced is worth keeping: a sheet is a file the user may have spent
    // an hour on, and this write is the moment it would otherwise be gone.
    const previous = await fs.readFile(full, 'utf8').catch(() => undefined);
    if (previous !== undefined && previous !== body.css) await snapshotSheet(body.name, previous);
    await fs.writeFile(full, body.css, 'utf8');
    // The revision the write produced, so the browser's baseline advances with it instead of
    // re-reading its own change and calling it somebody else's.
    json(res, 200, {
      ok: true,
      name: body.name,
      bytes: Buffer.byteLength(body.css),
      rev: await revisionOf(full),
    });
    return;
  }

  if (route === '/create' || route === '/import') {
    const full = safePath(body.name);
    if (full === undefined || await isSymlink(full)) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    const css = typeof body.css === 'string' ? body.css : '';
    if (route === '/create' && await fs.stat(full).then(() => true, () => false)) {
      json(res, 409, { ok: false, error: 'exists' });
      return;
    }
    await fs.mkdir(stylesDir(), { recursive: true });
    // An import overwrites by design, which is exactly when a snapshot matters.
    const previous = await fs.readFile(full, 'utf8').catch(() => undefined);
    if (previous !== undefined && previous !== css) await snapshotSheet(body.name, previous);
    await fs.writeFile(full, css, 'utf8');
    // A sheet that was just created or imported is meant to be in use: a switch
    // left over from a previous file of the same name would mute it on sight.
    await setActiveSheet(body.name, { enable: true });
    json(res, 200, { ok: true, name: body.name, bytes: Buffer.byteLength(css), rev: await revisionOf(full) });
    return;
  }

  if (route === '/rename') {
    const from = safePath(body.name);
    const to = safePath(body.to);
    if (from === undefined || to === undefined) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    if (await isSymlink(from)) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    if (body.name === body.to) {
      // Renaming a sheet to itself is a no-op rather than an error: the browser may not know the
      // two names match once whitespace and case are normalised.
      json(res, 200, { ok: true, name: body.name, renamed: false });
      return;
    }
    if (await fs.stat(to).then(() => true, () => false)) {
      json(res, 409, { ok: false, error: 'exists' });
      return;
    }
    const css = await fs.readFile(from, 'utf8').catch(() => undefined);
    if (css === undefined) {
      json(res, 404, { ok: false, error: 'not-found' });
      return;
    }
    // The OLD name's history moves with it, and the new name keeps its own if it had one. A
    // rename that lost the versions would make the one operation the row offers for a typo the
    // most destructive thing in the plugin.
    await fs.rename(from, to);
    const oldHistory = snapshotDir(body.name);
    const newHistory = snapshotDir(body.to);
    if (await fs.stat(oldHistory).then(stat => stat.isDirectory(), () => false)) {
      await fs.mkdir(newHistory, { recursive: true });
      for (const file of await fs.readdir(oldHistory).catch(() => [])) {
        const stamp = file.endsWith('.css') ? file.slice(0, -4) : '';
        if (!STAMP_PATTERN.test(stamp)) continue;
        await fs.rename(path.join(oldHistory, file), path.join(newHistory, file)).catch(() => {});
      }
      await fs.rmdir(oldHistory).catch(() => {});
    }
    // Bookkeeping follows the file: an active or muted sheet that kept its old name would come
    // back unmuted, and the switch would be pointing at a file that no longer exists.
    const renamedBook = await readBookkeeping();
    await writeBookkeeping({
      active: renamedBook.active === body.name ? body.to : renamedBook.active,
      disabled: renamedBook.disabled.map(name => (name === body.name ? body.to : name)),
    });
    json(res, 200, { ok: true, name: body.to, renamed: true, rev: await revisionOf(to) });
    return;
  }

  if (route === '/delete') {
    const full = safePath(body.name);
    if (full === undefined || await isSymlink(full)) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    // Existence is asked of the FILE, not of the listing: `listFiles` stops at MAX_FILES, so a
    // directory with more sheets than that would report its own tail as missing — measured with
    // 200+ sheets, where a legal rename target answered 404 on delete.
    const present = await fs.stat(full).then(stat => stat.isFile(), () => false);
    if (!present) {
      json(res, 404, { ok: false, error: 'not-found' });
      return;
    }
    // The last sheet is not deletable. The plugin's whole premise is that a sheet is in use, and
    // "no sheets at all" is a state the row has no screen for — an empty directory also takes the
    // seed sheet with it, so the next start would look like a fresh install.
    const others = (await fs.readdir(stylesDir()).catch(() => []))
      .filter(name => name !== body.name && isSheetName(name));
    if (others.length === 0) {
      json(res, 409, { ok: false, error: 'last-sheet' });
      return;
    }
    // Deleted is still reversible: the file is read into history first, which is the same promise
    // every write makes. Without it, this one button would be the only irreversible action here.
    const css = await fs.readFile(full, 'utf8').catch(() => undefined);
    if (css !== undefined) await snapshotSheet(body.name, css);
    await fs.unlink(full);
    const book = await readBookkeeping();
    const nextActive = book.active === body.name
      ? (others.includes('custom.css') ? 'custom.css' : others.sort((left, right) => left.localeCompare(right))[0])
      : book.active;
    await writeBookkeeping({
      active: nextActive,
      disabled: book.disabled.filter(name => name !== body.name),
    });
    json(res, 200, { ok: true, name: body.name, active: nextActive ?? null });
    return;
  }

  if (route === '/archive-and-reset') {
    // Reset by ARCHIVING, never by deleting: everything the plugin owns moves into
    // `.backup/<stamp>/`, which keeps a reset reversible and makes it the one-click backup as well.
    // Nothing here is removed — a user who pressed the wrong button finds their sheets one directory
    // deeper instead of gone.
    const dir = stylesDir();
    const stamp = String(Date.now());
    const target = path.join(dir, BACKUP_DIR, stamp);
    await fs.mkdir(target, { recursive: true });
    const moved = [];
    const skipped = [];
    const move = async (name) => {
      const from = path.join(dir, name);
      const present = await fs.lstat(from).then(() => true, () => false);
      if (!present) return;
      try {
        await fs.rename(from, path.join(target, name));
        moved.push(name);
      }
      catch (error) {
        // ⚠ Measured: on Windows a DIRECTORY that the plugin's own watcher has open cannot be
        // renamed (`EPERM`) — the files inside it move one at a time without complaint, but the
        // directory itself is held. A reset that failed on that would be a reset that never
        // happens, so the refusal is reported instead of thrown: the caller gets the list of what
        // stayed, and the UI tells the user to restart dsh to clear the handle.
        skipped.push({ name, code: error?.code ?? 'error' });
      }
    };
    // A whitelist rather than a directory scan: `.backup` itself must never be moved into, and the
    // seed sheet is the one file that stays — "reset" means "back to how it shipped", not "empty".
    for (const name of [WALLPAPER_RECORD, SETTINGS_RECORD, ACTIVE_FILE]) await move(name);
    for (const file of await listFiles(Infinity)) {
      if (file.name !== SEED_SHEET) await move(file.name);
    }
    for (const nested of [HISTORY_DIR, WALLPAPER_DIR]) await move(nested);
    // The seed sheet is written from the CALLER's copy rather than assumed to exist: a directory
    // that never had one (every run of the host test, and any user who renamed `custom.css`) would
    // otherwise come out of a reset with NO sheets — the one state the row has no screen for.
    await fs.writeFile(path.join(dir, SEED_SHEET), typeof body.css === 'string' ? body.css : '', 'utf8');
    // A fresh active pointer, so the next read finds the seed sheet rather than nothing.
    await writeBookkeeping({ active: SEED_SHEET, disabled: [] });
    json(res, 200, { ok: true, stamp, backup: target, moved, skipped, active: SEED_SHEET });
    return;
  }

  if (route === '/restore') {
    const full = safePath(body.name);
    if (full === undefined) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    if (typeof body.stamp !== 'string' || !STAMP_PATTERN.test(body.stamp)) {
      json(res, 400, { ok: false, error: 'bad-stamp' });
      return;
    }
    const snapshot = await fs.readFile(path.join(snapshotDir(body.name), body.stamp + '.css'), 'utf8').catch(() => undefined);
    if (snapshot === undefined) {
      json(res, 404, { ok: false, error: 'not-found' });
      return;
    }
    // The restore is reversible: what it replaces is snapshotted first, like any other write.
    const previous = await fs.readFile(full, 'utf8').catch(() => undefined);
    if (previous !== undefined && previous !== snapshot) await snapshotSheet(body.name, previous);
    await fs.mkdir(stylesDir(), { recursive: true });
    await fs.writeFile(full, snapshot, 'utf8');
    json(res, 200, {
      ok: true,
      name: body.name,
      stamp: body.stamp,
      bytes: Buffer.byteLength(snapshot),
      rev: await revisionOf(full),
    });
    return;
  }

  if (route === '/active') {
    const full = safePath(body.name);
    if (full === undefined || await isSymlink(full)) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    // A name that is merely missing is a separate case from a malformed one: the
    // client renders them differently, and "切换失败：bad-name" was a lie.
    if (!(await fs.stat(full).then(() => true, () => false))) {
      json(res, 404, { ok: false, error: 'not-found' });
      return;
    }
    await setActiveSheet(body.name);
    json(res, 200, { ok: true, name: body.name });
    return;
  }

  if (route === '/toggle') {
    const full = safePath(body.name);
    if (full === undefined || await isSymlink(full)) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    if (typeof body.enabled !== 'boolean') {
      json(res, 400, { ok: false, error: 'bad-body' });
      return;
    }
    if (!(await fs.stat(full).then(() => true, () => false))) {
      json(res, 404, { ok: false, error: 'not-found' });
      return;
    }
    const disabled = await queueBookkeeping(async () => {
      const book = await readBookkeeping();
      const kept = await pruneDisabled(book.disabled);
      const next = body.enabled
        ? kept.filter(name => name !== body.name)
        : [...new Set([...kept, body.name])];
      await writeBookkeeping({ active: book.active, disabled: next });
      return next;
    });
    json(res, 200, { ok: true, name: body.name, enabled: body.enabled, disabled });
    return;
  }

  if (route === '/open') {
    const full = safePath(body.name);
    if (full === undefined || await isSymlink(full)) {
      json(res, 400, { ok: false, error: 'bad-name' });
      return;
    }
    if (!(await fs.stat(full).then(() => true, () => false))) {
      json(res, 404, { ok: false, error: 'not-found' });
      return;
    }
    launchFile(full);
    json(res, 200, { ok: true, name: body.name });
    return;
  }

  json(res, 404, { ok: false, error: 'not-found' });
}

/**
 * Host plugin body: mount the stylesheet API behind the Connection fence.
 * Absent `webServer` (a non-Web composition) leaves the Host half inert — the
 * browser half then runs without file persistence instead of failing to load.
 * @param ctx - host cordis context.
 * @param options - `{ watch: false }` skips the filesystem watcher.
 */
export function apply(ctx, options = {}) {
  // Hand `/about` a way to ask which DSH release it is running under. `clientModules` publishes
  // `{ version, commit }` for the release it belongs to, and neither number is learnable from the
  // browser half. The lookup is stored, not its result: services activate around this plugin, and
  // asking at mount returned `undefined` on a real instance while the same call works a second
  // later. `get` is wrapped because a composition without that service is legal.
  readDshRelease = () => {
    try {
      return ctx.get('clientModules')?.release ?? null;
    }
    catch { return null; }
  };
  ctx.inject(['webServer'], (webCtx) => {
    // The sheet watcher: a doorbell for the browser half, which polls `/read` on its own timer
    // (see the client half). Started here rather than at module scope so a composition without a
    // web server does not open a directory handle it has nothing to do with.
    //
    // It can be skipped on request because it watches the STYLESHEET DIRECTORY, which the host
    // smoke test deletes at the end — and on Windows a watcher whose directory has been removed
    // keeps the process alive even after `close()`, so a test cannot outlive its own teardown.
    // Production never disposes this effect, so nothing about the real path depends on that.
    if (options.watch !== false) {
      webCtx.effect(() => watchSheets(() => {
        // Nothing to deliver: the browser asks. The listener exists so the watcher is not a
        // fire-and-forget handle nobody can see in a stack trace.
      }), 'dsh-custom-css: sheet watcher');
    }
    webCtx.effect(() => webCtx.webServer.register({
      kind: 'prefix',
      path: ROUTE,
      handler: async (req, res) => {
        const connection = ctx.get('connection');
        const reject = connection?.requestRejection;
        if (typeof reject !== 'function') {
          // Fail closed: without the fence this route would be reachable by any
          // client that can reach the port, including unpaired LAN hosts.
          res.writeHead(503, { 'content-type': 'text/plain; charset=utf-8' });
          res.end('dsh-custom-css: connection fence unavailable');
          return;
        }
        // A fence that throws must fail closed: an escaping exception would skip the
        // 503 path entirely and reach the client as a hung or 500 request.
        let rejection;
        try {
          rejection = reject.call(connection, req);
        }
        catch {
          res.writeHead(503, { 'content-type': 'text/plain; charset=utf-8' });
          res.end('dsh-custom-css: connection fence failed');
          return;
        }
        if (rejection !== undefined) {
          res.writeHead(rejection, { 'content-type': 'text/plain; charset=utf-8' });
          res.end(rejection === 401 ? 'unauthorized' : 'forbidden');
          return;
        }
        try {
          await handle(req, res);
        }
        catch (error) {
          json(res, 500, { ok: false, error: String(error) });
        }
      },
    }), 'dsh-custom-css: stylesheet api');
  });
}
